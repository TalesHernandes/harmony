import { test, expect, Person } from './fixtures';
import { mkdirSync } from 'node:fs';

test('image viewer anchors wheel zoom, pans, resets and toggles actual pixels', async ({ browser }) => {
  const person = await Person.create(browser, 'paritysevenb');
  const page = person.page;
  await page.setViewportSize({width:1280,height:800});
  const fixture = await browser.newPage({viewport:{width:1600,height:900}});
  await fixture.setContent('<body style="margin:0;background:linear-gradient(45deg,#0485c8 50%,#175ac8 50%);height:100vh"></body>');
  const buffer = await fixture.screenshot(); await fixture.close();
  await page.locator('[data-composer] input[type="file"]').setInputFiles({name:'zoom.png',mimeType:'image/png',buffer});
  await page.getByRole('button',{name:'Ampliar zoom.png',exact:true}).click();
  const viewer = page.locator('[data-lightbox]'), image = viewer.locator('img');
  await expect(image).toHaveJSProperty('naturalWidth',1600);
  const matrix = () => image.evaluate(el => {const m=new DOMMatrix(getComputedStyle(el).transform);return {scale:m.a,x:m.e,y:m.f};});
  const box = (await image.boundingBox())!;
  await page.mouse.move(box.x+box.width*.75,box.y+box.height*.5);
  await page.mouse.wheel(0,-240);
  await expect.poll(async () => (await matrix()).scale).toBeGreaterThan(1.5);
  expect((await matrix()).x).toBeLessThan(0);
  const before = await matrix();
  await page.mouse.move(640,400);await page.mouse.down();await page.mouse.move(690,430,{steps:5});await page.mouse.up();
  await expect.poll(async () => (await matrix()).x).toBeCloseTo(before.x+50,1);
  mkdirSync('windows/app/test-output/round7b-web',{recursive:true});
  await page.screenshot({path:'windows/app/test-output/round7b-web/zoom-pan.png'});
  await viewer.getByRole('button',{name:'Tamanho ajustado',exact:true}).click();
  expect(await matrix()).toEqual({scale:1,x:0,y:0});
  await image.dblclick();
  const naturalScale = await image.evaluate(el => (el as HTMLImageElement).naturalWidth / el.clientWidth);
  await expect.poll(async () => (await matrix()).scale).toBeCloseTo(naturalScale,3);
  await image.dblclick();expect((await matrix()).scale).toBe(1);
  await viewer.getByRole('button',{name:'Aumentar zoom',exact:true}).click();expect((await matrix()).scale).toBe(1.25);
  await viewer.getByRole('button',{name:'Diminuir zoom',exact:true}).click();expect((await matrix()).scale).toBe(1);
  await page.screenshot({path:'windows/app/test-output/round7b-web/fit.png'});
  await page.keyboard.press('Escape');await expect(viewer).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'fechar',exact:true}).click();
  await expect(page.locator('aside')).toHaveCount(0);
  await page.getByRole('button',{name:'Ampliar zoom.png',exact:true}).click();
  await expect(viewer).toBeVisible();
  const mobileImage=(await image.boundingBox())!, controls=(await viewer.locator('.image-zoom-controls').boundingBox())!;
  expect(mobileImage.y+mobileImage.height).toBeLessThanOrEqual(controls.y);
  await page.screenshot({path:'windows/app/test-output/round7b-web/mobile-fit.png'});
  await page.keyboard.press('Escape');await expect(viewer).toHaveCount(0);
  await person.close();
});
