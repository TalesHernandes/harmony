import { test, expect, Person } from './fixtures';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

test('photo actions and composer geometry stay consistent across harmony', async ({ browser }) => {
  const out = 'windows/app/test-output/round6-cont-web-evidence';
  mkdirSync(out, { recursive: true });
  const owner = await Person.create(browser, 'r6evidenceowner');
  const peer = await Person.create(browser, 'r6evidencepeer');
  const page = owner.page;
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.evaluate(() => document.fonts.ready);
  await owner.inChannel('geral').fill('Texto em negrito alinhado');
  await page.screenshot({ path: `${out}/composer-typed.png` });
  const geometry = await page.locator('[data-composer-island]').evaluate(island => {
    const field = island.querySelector('textarea')!;
    return { islandHeight: island.getBoundingClientRect().height, textInset: field.getBoundingClientRect().left - island.getBoundingClientRect().left + parseFloat(getComputedStyle(field).paddingLeft) };
  });
  expect(geometry).toEqual({ islandHeight: 48, textInset: 90 });
  writeFileSync(`${out}/geometry.json`, JSON.stringify(geometry, null, 2));
  await owner.inChannel('geral').fill('@');
  await page.locator('[data-mentions]').waitFor();
  const marker = await page.locator('.mention-option.is-selected').evaluate(el => {
    const style = getComputedStyle(el, '::before');
    return { width: style.width, color: style.backgroundColor, radius: style.borderRadius, top: style.top, bottom: style.bottom };
  });
  expect(marker.width).toBe('3px'); expect(marker.color).toBe('rgb(4, 133, 247)');
  writeFileSync(`${out}/mention-marker.json`, JSON.stringify(marker, null, 2));
  await page.screenshot({ path: `${out}/mentions.png` });
  await owner.inChannel('geral').fill('');
  await page.getByRole('button', { name: 'Meu perfil', exact: true }).click();
  const profile = page.getByRole('dialog', { name: 'perfil de r6evidenceowner', exact: true });
  await profile.locator('[data-face]').click();
  const chooser = page.waitForEvent('filechooser');
  await profile.getByRole('button', { name: 'Alterar foto', exact: true }).click();
  await (await chooser).setFiles('web/harmony/public/icon-192.png');
  await page.getByRole('dialog', { name: 'Editar foto', exact: true }).getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(profile.locator('[data-face] img')).toHaveJSProperty('naturalWidth', 256);
  await profile.locator('[data-face]').hover();
  await page.screenshot({ path: `${out}/own-photo-pencil.png` });
  await profile.locator('[data-face]').click();
  await page.screenshot({ path: `${out}/own-photo-menu.png` });
  const removePhoto=profile.getByRole('button', { name: 'Remover foto', exact: true });
  await expect(removePhoto).toHaveCSS('background-color', 'rgb(219, 59, 62)');
  await removePhoto.hover();
  await expect(removePhoto).toHaveCSS('background-color', 'rgb(225, 84, 81)');
  await expect(removePhoto).toHaveCSS('color', 'rgb(252, 252, 252)');
  await page.screenshot({ path: `${out}/remove-photo-hover.png` });
  await profile.getByRole('button', { name: 'Ver foto', exact: true }).click();
  await page.locator('[data-lightbox] img').waitFor();
  await page.screenshot({ path: `${out}/profile-photo-viewer.png` });
  await page.keyboard.press('Escape');
  await profile.getByRole('button', { name: 'fechar', exact: true }).click();
  await page.locator('aside button[data-person="r6evidencepeer"]').first().click();
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Ligar', exact: true })).toBeVisible();
  await page.screenshot({ path: `${out}/other-profile-call.png` });
  await page.keyboard.press('Escape');
  await page.locator('[data-composer] input[type="file"]').setInputFiles({ name: 'preview.png', mimeType: 'image/png', buffer: readFileSync('web/harmony/public/icon-192.png') });
  await page.getByRole('button', { name: 'Ampliar preview.png', exact: true }).click();
  await expect(page.locator('[data-lightbox] img')).toHaveJSProperty('naturalWidth', 192);
  await page.screenshot({ path: `${out}/pending-image-viewer.png` });
  await owner.close(); await peer.close();
});
