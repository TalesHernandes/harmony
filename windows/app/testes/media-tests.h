#pragma once
#include "../../native/src/media-policy.h"
#include "../../native/gpu/capture-hold.h"
inline void RunMediaTests(void (*check)(bool,const char*)) {
  using namespace media;
  gpu::CaptureHold hold;
  using gpu::HoldReason;
  check(!hold.Due(1000000,false,HoldReason::Minimized),"capture never invents a first black frame");
  hold.Fresh(1000000);hold.Stamp(1000000);
  check(!hold.Due(1199999,true,HoldReason::Stalled)&&hold.Due(1200000,true,HoldReason::Stalled),"capture idle deadline repeats a static source after 200 ms");
  check(hold.Due(1000001,true,HoldReason::Minimized),"capture minimizes immediately before any black WGC update");
  hold.notice=HoldReason::Minimized;hold.Stamp(1000001);
  check(!hold.Due(hold.output_us+199999,true,HoldReason::Minimized)&&hold.Due(hold.output_us+200000,true,HoldReason::Minimized),"capture holds at five fps without spinning");
  check(gpu::CaptureHold::kIntervalUs<350000,"capture heartbeat fits Android's video-only RTP progress sample");
  check(hold.Due(1000002,true,HoldReason::Closed),"capture closure replaces minimized caption immediately");
  auto stamp=hold.Stamp(900000);check(stamp>1000001,"capture resumed old compositor time cannot reverse output timestamps");
  hold.Fresh(2000000);check(hold.notice==HoldReason::None&&!hold.Due(2000001,true,HoldReason::Stalled),"capture restored source clears notice and stall deadline");
  auto eventIs=[](const char* event,const char* expected){return event&&std::string(event)==expected;};
  const std::wstring own=LR"(C:\Harmony\harmony.exe)",windows=LR"(C:\Windows)";
  auto follows=[&](const wchar_t* a,const wchar_t* b){return FollowFolder(a,b,own,windows);};
  check(follows(LR"(C:\Jogos\League of Legends\LeagueClientUx.exe)",LR"(C:\Jogos\League of Legends\Game\League of Legends.exe)"),"follow game in child folder");
  check(follows(LR"(C:\Jogos\League\a.exe)",LR"(c:/jogos/LEAGUE/b.exe)"),"follow same folder ignores ASCII case and separators");
  check(follows(LR"(C:\Jogos\League\Ux\a.exe)",LR"(C:\Jogos\League\b.exe)"),"follow immediate parent folder");
  check(!follows(LR"(C:\Jogos\League\Ux\a.exe)",LR"(C:\Jogos\League\Other\b.exe)"),"follow never widens to sibling folder");
  check(!follows(LR"(C:\Jogos\League\a.exe)",LR"(C:\Jogos\LeagueOther\b.exe)"),"follow requires directory boundary");
  check(!follows(LR"(C:\Jogos\League\Ux\a.exe)",LR"(C:\Jogos\b.exe)"),"follow rejects grandparent");
  check(follows(LR"(C:\Jogos\Ação\a.exe)",LR"(C:\Jogos\AÇÃO\Partida\b.exe)"),"follow accented folder and case");
  check(!follows(LR"(C:\Windows\a.exe)",LR"(C:\Windows\b.exe)"),"follow rejects Windows");
  check(!follows(LR"(C:\Windows\System32\a.exe)",LR"(C:\Windows\System32\b.exe)"),"follow rejects System32");
  check(!follows(LR"(C:\Program Files\a.exe)",LR"(C:\Program Files\Game\b.exe)"),"follow rejects generic Program Files source");
  check(!follows(LR"(C:\Program Files\Game\a.exe)",LR"(C:\Program Files\b.exe)"),"follow rejects generic parent candidate");
  check(!follows(LR"(C:\Harmony\a.exe)",LR"(C:\Harmony\Game\b.exe)"),"follow rejects own folder");
  check(!follows(LR"(C:\Game\a.exe)",LR"(C:\Harmony\b.exe)"),"follow rejects own candidate");
  check(!follows(LR"(C:\Game\a.exe)",LR"(D:\Game\b.exe)"),"follow rejects other drive");
  check(!follows(LR"()",LR"(C:\Game\b.exe)")&&!follows(LR"(C:\Game\a.exe)",LR"()"),"follow missing process identity is denied");
  check(!follows(LR"(C:\Game\a.exe)",LR"(C:\Game\..\Other\b.exe)"),"follow rejects dot traversal");
  check(!follows(LR"(Game\a.exe)",LR"(Game\b.exe)"),"follow rejects relative paths");
  check(FollowBetter({true,10},{false,10000})&&!FollowBetter({false,10000},{true,10}),"follow foreground wins over area");
  check(FollowBetter({false,200},{false,100})&&!FollowBetter({false,100},{false,200}),"follow largest area wins without foreground");
  check(!FollowBetter({false,100},{false,100}),"follow equal area preserves enumeration order");
  FollowSearch search;
  check(!search.Poll(false,1000)&&!search.started,"follow does not search minimized live window");
  check(search.Poll(true,1000)&&!search.Poll(true,1499)&&search.Poll(true,1500),"follow polls every 500 ms");
  check(search.Poll(true,60999)&&!search.Poll(true,61000)&&!search.Poll(true,62000),"follow stops at 60 seconds");
  Transmission stream;
  check(!stream.Choose(false)&&!stream.active,"media invalid selection preserves idle");
  check(stream.Choose(true)&&stream.active&&stream.revision==1,"media selection starts transmission");
  check(stream.Choose(true)&&stream.active&&stream.revision==2,"media replacement preserves transmission");
  check(!stream.Choose(false)&&stream.active&&stream.revision==2,"media invalid replacement preserves live");
  check(eventIs(stream.Observe(true,false,false,1920,1080),"resized")&&stream.Observe(true,false,false,1920,1080)==nullptr,"media resize emits once per size");
  check(eventIs(stream.Observe(true,false,true,1920,1080),"minimized")&&stream.active,"media minimized retains transmission");
  check(stream.Observe(true,false,true,0,0)==nullptr&&stream.width==1920,"media minimized ignores zero capture size");
  check(eventIs(stream.Observe(true,false,false,1280,720),"transmitting"),"media restored resumes transmission");
  check(eventIs(stream.Observe(true,false,false,1280,720),"resized"),"media restored size updates once");
  check(eventIs(stream.Observe(false,true,false,0,0),"window_closed")&&!stream.active,"media closed window stops before lost capture");
  stream.Choose(true);
  check(eventIs(stream.Observe(false,false,false,0,0),"window_closed")&&stream.active,"media closed window retains live notice track");
  check(stream.Observe(false,false,false,0,0)==nullptr&&stream.active,"media closed notice emits once without unpublishing");
  check(stream.Choose(true)&&eventIs(stream.Observe(false,false,false,0,0),"window_closed"),"media replacement clears closed notice");
  stream.Choose(true);check(eventIs(stream.Observe(true,true,false,0,0),"capture_lost")&&!stream.active,"media lost capture stops transmission");
  stream.Choose(true);stream.Stop();check(!stream.active&&stream.Observe(false,true,false,0,0)==nullptr,"media explicit stop is terminal");
  int mic=1,cam=2,screen=3,sound=4;
  check(Outgoing("cam",&mic,&cam,&screen,&sound)==&cam && Outgoing("screen",&mic,&cam,&screen,&sound)==&screen,"media camera and screen occupy independent slots");
  check(Outgoing("screen_audio",&mic,&cam,&screen,&sound)==&sound&&Outgoing("unknown",&mic,&cam,&screen,&sound)==nullptr,"media second audio and unnamed receiver slots");
  check(Capturable({true,false,false,false,false}),"media normal window listed");
  check(!Capturable({false,false,false,false,false}),"media invisible window omitted");
  check(!Capturable({true,true,false,false,false}),"media tool window omitted");
  check(!Capturable({true,false,true,false,false}),"media cloaked window omitted");
  check(!Capturable({true,false,false,true,false}),"media own window omitted");
  check(!Capturable({true,false,false,false,true}),"media protected window omitted");
  check(Layer(1199,1)==1&&Layer(1200,1)==0,"media high boundary 1200 physical pixels");
  check(Layer(599,1)==2&&Layer(600,1)==1,"media medium boundary 600 physical pixels");
  check(Layer(400,3)==0&&Layer(300,2)==1,"media DPI multiplies drawn width");
  check(Layer(1920,1,false)==2&&Layer(0,1)==2,"media hidden viewer low layer");
  LayerRequest request;request.Resize(1920,1,true,1000);
  check(request.Ready(1399)==-1&&request.Ready(1400)==0,"media size waits 400ms");
  request.Resize(300,1,true,1300);
  check(request.Ready(1699)==-1&&request.Ready(1700)==2,"media resize restarts debounce");
  LayerRequest away;away.Resize(1920,1,true,0);
  check(away.PauseMove(100000)==0,"media a tile being looked at is never paused");
  away.Look(false,1000);away.Look(false,20000);
  check(away.PauseMove(30999)==0&&away.PauseMove(31000)==1,"media a tile pauses only after 30 s away, counted from when it left");
  away.Look(true,25000);away.Look(false,26000);
  check(away.PauseMove(55999)==0&&away.PauseMove(56000)==1,"media a peek back restarts the away wait");
  away.Paused(true,56000);away.requested=0;
  check(away.PauseMove(90000)==0,"media a paused tile is not paused twice");
  away.Resize(1920,1,true,90000);
  check(away.PauseMove(90000)==-1,"media looking again resumes at once");
  away.Paused(false,90000);
  check(away.requested==-1&&away.PauseMove(90001)==0,"media a resumed tile asks for its size again");
  away.Resize(1920,1,false,100000);
  check(away.desired==2&&away.PauseMove(130000)==1,"media a hidden window lowers the layer first and pauses after the wait");
  LayerRequest retry; retry.desired=0;
  check(retry.Complete(0,false,0)&&retry.retryDelay==500,"media first layer failure reports and waits 500ms");
  retry.Resize(300,1,true,50);
  check(!retry.CanAttempt(499)&&retry.Ready(500)==2,"media resize preserves retry and sends newest desire");
  retry.Resize(1920,1,true,499);
  check(retry.Ready(500)==0,"media late resize changes desired layer without extending failure wait");
  int64_t at=500;
  for(int delay:{1000,2000,4000,5000,5000}) {
    check(!retry.Complete(2,false,at)&&retry.retryDelay==delay,"media repeated failure doubles delay up to 5000ms without logging");
    check(!retry.CanAttempt(at+delay-1)&&retry.CanAttempt(at+delay),"media retry boundary is exact");at+=delay;
  }
  check(retry.Complete(2,true,at)&&retry.requested==2&&retry.retryDelay==0&&retry.retryAt==0,"media recovery reports and clears backoff");
  check(!retry.Complete(2,true,at),"media healthy success does not report recovery");
  check(retry.Complete(0,false,at)&&retry.retryDelay==500,"media next failure sequence starts again at 500ms");
  DecodeHealth health;
  check(!health.Sample(9,0,20000),"media fewer than ten decode frames ignored");
  check(!health.Sample(90,10,20000)&&!health.Sample(90,10,21000),"media two bad decode samples hold");
  check(health.Sample(90,10,22000)&&health.cap==1,"media three bad decode samples lower cap");
  check(!health.Sample(90,10,41999)&&health.bad==0,"media decode holds twenty seconds");
  for(int i=0;i<19;++i) check(!health.Sample(100,0,42000+i*1000),"media decode clean hysteresis");
  check(health.Sample(100,0,61000)&&health.cap==0,"media twenty clean samples lift cap");
  health.Sample(90,10,81000);health.Sample(90,10,82000);health.Sample(90,10,83000);
  check(health.fails==2,"media repeated decoder failure doubles clean wait");
  for(int i=0;i<39;++i) check(!health.Sample(100,0,103000+i*1000),"media repeated clean hysteresis");
  check(health.Sample(100,0,142000)&&health.cap==0,"media forty clean samples lift repeated cap");
  auto window=SoundTarget(77,99),monitor=SoundTarget(0,99);
  check(window.pid==77&&window.include,"media window sound includes selected tree");
  check(monitor.pid==99&&!monitor.include,"media monitor sound excludes own tree");
  check(!SoundIncludes(window,99,false)&&!SoundIncludes(monitor,99,true),"media call process excluded from both game audio policies");
  check(SoundIncludes(window,78,true)&&SoundIncludes(monitor,77,false),"media game and children included");
  check(ScreenCeiling(1080,60)==15000000&&ScreenCeiling(1080,30)==12000000&&ScreenCeiling(1080,15)==9000000,"media web 1080 ceilings");
  check(ScreenCeiling(720,60)==12000000&&ScreenCeiling(720,30)==9000000&&ScreenCeiling(720,15)==6000000,"media web 720 ceilings");
  check(ScreenCeiling(480,60)==6000000&&ScreenStart(1080,60)==6000&&ScreenStart(720,30)==3600,"media web start and 480 ceiling");
}
