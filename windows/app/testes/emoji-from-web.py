"""Generate native emoji data. Python stdlib only; uses the installed Node's
Unicode engine (the same property escapes/NFD/lowercase used by the web).
No packages, network, copied search implementation, or runtime Node dependency.
Run from any directory; --check fails if the checked-in output is stale.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import unicodedata

HERE = Path(__file__).resolve().parent.parent
ROOT = HERE.parent.parent
OUTPUT = HERE / 'src/emoji-data.inc'


def node(source):
    return json.loads(subprocess.check_output(
        ['node', '--input-type=module', '-e', source], cwd=ROOT, encoding='utf-8'))


def literal(s):
    return json.dumps(s, ensure_ascii=False)


def generate():
    source = (ROOT / 'web/harmony/src/emoji.ts').read_text(encoding='utf-8')
    twemoji = (ROOT / 'web/harmony/src/Twemoji.tsx').read_text(encoding='utf-8')
    declarations = twemoji[twemoji.index('const PART ='):twemoji.index('// Characters that')]
    regex = node('console.log(JSON.stringify((new Function(' +
                 json.dumps(declarations + '\nreturn {PART, SOURCE};') + '))()));')
    part = r'\p{Extended_Pictographic}(?:\uFE0F|\p{Emoji_Modifier})?[\u{E0020}-\u{E007F}]*'
    pattern = r'\p{Regional_Indicator}{2}|[#*0-9]\uFE0F?\u20E3|' + part + r'(?:\u200D' + part + ')*'
    if regex != {'PART': part, 'SOURCE': pattern}:
        raise ValueError('Twemoji SOURCE/PART changed; update the native matcher before regenerating')
    # Node 24 loads this type-only TypeScript directly, with no transpilation.
    data = node("""
import {GROUPS, search, plain} from './web/harmony/src/emoji.ts';
const properties = ['Extended_Pictographic', 'Emoji_Presentation',
 'Regional_Indicator', 'Emoji_Modifier', 'Cased', 'Case_Ignorable', 'Assigned'];
const ranges = Object.fromEntries(properties.map(p => [p, []]));
const tests = properties.map(p => new RegExp('^\\\\p{' + p + '}$', 'u'));
const nfd = [], lower = [], marks = [];
for (let cp = 0; cp <= 0x10ffff; ++cp) {
 if (cp >= 0xd800 && cp <= 0xdfff) continue;
 const s = String.fromCodePoint(cp);
 if (/^\\p{M}$/u.test(s)) marks.push(cp);
 properties.forEach((p, i) => {
  if (!tests[i].test(s)) return;
  const a = ranges[p], last = a.at(-1);
  if (last && last[1] + 1 === cp) last[1] = cp;
  else a.push([cp, cp]);
 });
 // Hangul decomposition is algorithmic in C++, avoiding 11,172 table rows.
 if (!(cp >= 0xac00 && cp <= 0xd7a3) && s.normalize('NFD') !== s)
  nfd.push([cp, [...s.normalize('NFD')].map(c => c.codePointAt(0))]);
 if (s.toLowerCase() !== s)
  lower.push([cp, [...s.toLowerCase()].map(c => c.codePointAt(0))]);
}
console.log(JSON.stringify({groups: GROUPS, ranges, nfd, lower, marks,
 unicode: process.versions.unicode,
 expected: Object.fromEntries(['fogo','coracao','coração','rost','fogo top','',
 '  FÓGO  ', 'obj', 'bandeira'].map(q => [q,search(q)])),
 plain: Object.fromEntries([' Coração ', 'İ', 'ΟΣ', 'ΟΣΑ', 'A\\u0315\\u0300',
 '각', 'Ǻ', 'Ω', '\\u1e9e', '\\ufeff FOGO\\u00a0'].map(q => [q,plain(q)]))}));
""")
    lines = ['// Generated by emoji-from-web.py; DO NOT EDIT.',
             '// emoji.ts SHA256: ' + hashlib.sha256(source.encode()).hexdigest(),
             '// Twemoji.tsx SHA256: ' + hashlib.sha256(twemoji.encode()).hexdigest(),
             '// Node Unicode ' + data['unicode'] + '; Python Unicode ' + unicodedata.unidata_version,
             'static const std::vector<EmojiGroup> kEmojiGroups = {']
    for group in data['groups']:
        lines.append('  {' + literal(group['name']) + ', ' + literal(group['emoji'][0][0]) + ', {')
        for emoji, words in group['emoji']:
            lines.append('    {' + literal(emoji) + ', ' + literal(words) + '},')
        lines.append('  }},')
    lines.append('};')
    for name, ranges in data['ranges'].items():
        if name == 'Assigned':
            continue
        lines.append('static constexpr Range k' + name.replace('_', '') + '[] = {')
        lines.extend(f'  {{0x{a:x}, 0x{b:x}}},' for a, b in ranges)
        lines.append('};')
    for name in ['nfd', 'lower']:
        lines.append('static constexpr Mapping k' + name.capitalize() + '[] = {')
        for cp, points in data[name]:
            value = ''.join('\\U%08x' % p for p in points)
            lines.append(f'  {{0x{cp:x}, U"{value}"}},')
        lines.append('};')
    # Python and Node may ship different Unicode versions. Use Python's
    # stable old combining classes as probes, then ask Node's NFD ordering
    # about every mark (including characters newer than Python's database).
    classes = sorted({unicodedata.combining(chr(cp)) for cp in data['marks']} - {0})
    reps = [next(cp for cp in data['marks']
                 if unicodedata.combining(chr(cp)) == cls
                 and unicodedata.normalize('NFD', chr(cp)) == chr(cp))
            for cls in classes]
    combining = node('const marks = ' + json.dumps(data['marks']) + ';\n'
                     'const reps = ' + json.dumps(reps) + ';\n' + """
const result = [];
for (const cp of marks) {
 const c = String.fromCodePoint(cp);
 // Only decomposition-stable scalars can survive the NFD map above.
 if (c.normalize('NFD') !== c) continue;
 let swaps = false, below = 0, equal = -1;
 reps.forEach((r, i) => {
  if (r === cp) { equal = i; return; }
  const p = String.fromCodePoint(r);
  const a = ('a' + c + p).normalize('NFD');
  const b = ('a' + p + c).normalize('NFD');
  if (a === 'a' + p + c) { swaps = true; ++below; }
  else if (b === 'a' + c + p) swaps = true;
  else equal = i;
 });
 // Zero-class marks never reorder with any probe. Ranks preserve order
 // without depending on Python knowing the numeric class of a new mark.
 if (swaps) result.push([cp, equal >= 0 ? 2 * (equal + 1) : 2 * below + 1]);
}
console.log(JSON.stringify(result));
""")
    lines.append('static constexpr Combining kCombining[] = {')
    lines.extend(f'  {{0x{cp:x}, {cls}}},' for cp, cls in combining)
    lines.append('};')
    lines.append('#ifdef HARMONY_EMOJI_TEST_ORACLES')
    lines.append('static const std::vector<std::pair<std::string, std::vector<std::string>>> kSearchOracle = {')
    for query, results in data['expected'].items():
        lines.append('  {' + literal(query) + ', {' + ', '.join(map(literal, results)) + '}},')
    lines.append('};')
    lines.append('static const std::vector<std::pair<std::string, std::string>> kPlainOracle = {')
    lines.extend('  {' + literal(q) + ', ' + literal(v) + '},' for q, v in data['plain'].items())
    lines.extend(['};', '#endif', ''])
    return '\n'.join(lines).encode('utf-8'), data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated, data = generate()
    if args.check:
        # Git's Windows checkout may use CRLF; generated data is identical.
        if not OUTPUT.exists() or OUTPUT.read_bytes().replace(b'\r\n', b'\n') != generated:
            print('emoji-data.inc is stale; run python windows/app/testes/emoji-from-web.py', file=sys.stderr)
            return 1
    else:
        OUTPUT.write_bytes(generated)
    entries = sum(len(g['emoji']) for g in data['groups'])
    print(f'{OUTPUT.name}: {len(generated)} bytes, {entries} entries, {len(data["groups"])} groups; check={args.check}')
    for q in ['fogo', 'coracao', 'coração']:
        print(json.dumps({q: data['expected'][q]}, ensure_ascii=True))
    return 0


if __name__ == '__main__':
    sys.exit(main())
